using Coworkee.Domain;
using Coworkee.Infrastructure.Persistence;
using MyApp.Contracts.Catalog;
using Nextended.Core.Attributes;
using Nextended.Core.Enums;
using Nextended.Core.Facets;

namespace MyApp.Catalog.Domain;

[Realtime(CatalogPermissions.Products.View)]
[AutoGenerateDto(Namespace = "MyApp.Contracts.Catalog", MappingStrategy = DtoMappingStrategy.Mapperly)]
public sealed class Product : AuditedEntity, IMultiTenant, ISoftDelete
{
    public required string Name { get; set; }

    public string? Barcode { get; set; }

    public string? Description { get; set; }

    public string? ImageDataUrl { get; set; }

    [ProvideFacet(Label = "Rate", Type = FacetType.Range, Order = 1)]
    public decimal Rate { get; set; }

    [ProvideFacet(Label = "Brand", ValuePath = "BrandId", LabelPath = "Brand.Name", ValueType = typeof(Guid))]
    public Guid BrandId { get; set; }

    public Brand? Brand { get; set; }

    public Guid TenantId { get; set; }

    public bool IsDeleted { get; set; }

    public DateTimeOffset? DeletedAt { get; set; }

    public Guid? DeletedBy { get; set; }
}
